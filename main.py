def print_hi(name):
    """
    最普通的函数：接一个 name，打印一句问候。

    输入 name：谁给的 —— 下面调用时写死的 'PyCharm'。
    加工：把 name 插进 f-string 拼成一句话，没有任何处理。
    输出：没有返回值（不写 return 就等于 return None），结果直接打印给人看。
    """
    # f'Hi, {name}' 是 f-string：花括号里的变量会被替换成它的值。
    print(f'Hi, {name}')


# if __name__ == '__main__'：只有"直接运行这个文件"时才执行下面的代码；
# 被别人 import 时不执行。这是"既能当脚本又能当模块"的标准写法。
if __name__ == '__main__':
    print_hi('PyCharm')


