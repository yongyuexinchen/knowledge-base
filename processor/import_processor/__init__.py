# processor/import_processor/__init__.py
# ================================================================================
# 空文件，作用：让 import_processor 成为一个包（原因见 processor/__init__.py）。
#
# ── 这个包里每个文件管什么 ───────────────────────────────────────────────────
#
#   文件名           角色              一句话说明
#   ─────────────── ──────────────── ─────────────────────────────────────────
#   state.py        数据定义          贯穿全流程的大字典长什么样、谁写谁读
#   base.py         节点外壳          所有节点共用的父类（打日志/包错误/转交数据）
#   config.py       配置              所有可调参数集中在这，从 .env 读进来
#   exceptions.py   错误类型          出错时让错误"说清楚是谁、在哪出的"
#   nodes/          业务层            8 个节点，真正加工数据的地方
#
#   一句话：**state 是数据的形状，base 是通道，nodes 是加工，**
#           **config 和 exceptions 是两条不碰数据的外围线。**
#
#   完整数据流向（谁读哪个字段、谁写哪个字段）→ docs/FLOW.md
#
# ── 分层的好处 ───────────────────────────────────────────────────────────────
#   加第 8 个节点时：只需在 nodes/ 下新建文件、继承 BaseNode、实现 process，
#   其余文件一行都不用动。
# ================================================================================
